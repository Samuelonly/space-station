/// Settings namespace backed by UserDefaults. Keys are namespaced to avoid
/// collisions with other apps.
enum SS {
    nonisolated(unsafe) private static let ud = UserDefaults.standard
    private static func key(_ name: String) -> String { "com.samuelonly.spacestation.\(name)" }

    // Timer interval. Fixed for M1 (settings UI is M4).
    static var clipboardCheckInterval: Double { 0.5 }

    // Defaults.Keys+Names.swift:30-32 — supported item types.
    static var enabledPasteboardTypes: Set<NSPasteboard.PasteboardType> {
        Set(StorageType.all.types)
    }

    // Defaults.Keys+Names.swift:39-49 — type-level secret sources (copied values).
    static var ignoredPasteboardTypes: Set<String> {
        get {
            ud.object(forKey: key("ignoredPasteboardTypes")) as? Set<String> ?? Set([
                "Pasteboard generator type",
                "com.agilebits.onepassword",
                "com.typeit4me.clipping",
                "de.petermaurer.TransientPasteboardType",
                "net.antelle.keeweb"
            ])
        }
        set { ud.set(newValue, forKey: key("ignoredPasteboardTypes")) }
    }

    // Defaults.Keys+Names.swift:38 — app-level hard exclusion.
    // Our addition (PRD: 忽略应用程序): preloaded credential managers.
    static var ignoredApps: [String] {
        get {
            ud.object(forKey: key("ignoredApps")) as? [String] ?? [
                "com.agilebits.onepassword.osx",
                "com.bitwarden.desktop",
                "com.apple.keychainaccess",
                "com.apple.Passwords"
            ]
        }
        set { ud.set(newValue, forKey: key("ignoredApps")) }
    }

    static var ignoreAllAppsExceptListed: Bool {
        get { ud.bool(forKey: key("ignoreAllAppsExceptListed")) }
        set { ud.set(newValue, forKey: key("ignoreAllAppsExceptListed")) }
    }

    static var ignoreRegexp: [String] {
        get { ud.stringArray(forKey: key("ignoreRegexp")) ?? [] }
        set { ud.set(newValue, forKey: key("ignoreRegexp")) }
    }

    // Status-item ⌥ / ⌥⇧ gestures toggle these (AppDelegate.swift:192-195).
    static var ignoreEvents: Bool {
        get { ud.bool(forKey: key("ignoreEvents")) }
        set { ud.set(newValue, forKey: key("ignoreEvents")) }
    }

    static var ignoreOnlyNextEvent: Bool {
        get { ud.bool(forKey: key("ignoreOnlyNextEvent")) }
        set { ud.set(newValue, forKey: key("ignoreOnlyNextEvent")) }
    }

    // Our enhancement (HTML §21.5.3): add the explicit Handoff ignore switch
    // the PRD asks for.
    static var ignoreHandoff: Bool {
        get {
            if ud.object(forKey: key("ignoreHandoff")) == nil { return true }
            return ud.bool(forKey: key("ignoreHandoff"))
        }
        set { ud.set(newValue, forKey: key("ignoreHandoff")) }
    }

    static var historySize: Int {
        get {
            let v = ud.integer(forKey: key("historySize"))
            return v == 0 ? 200 : v
        }
        set { ud.set(newValue, forKey: key("historySize")) }
    }

    static var sortBy: Sorter.By {
        get { Sorter.By(rawValue: ud.string(forKey: key("sortBy")) ?? "") ?? .lastCopiedAt }
        set { ud.set(newValue.rawValue, forKey: key("sortBy")) }
    }

    static var pinTo: PinPosition {
        get { PinPosition(rawValue: ud.string(forKey: key("pinTo")) ?? "") ?? .top }
        set { ud.set(newValue.rawValue, forKey: key("pinTo")) }
    }

    static var showSpecialSymbols: Bool {
        get {
            if ud.object(forKey: key("showSpecialSymbols")) == nil { return true }
            return ud.bool(forKey: key("showSpecialSymbols"))
        }
        set { ud.set(newValue, forKey: key("showSpecialSymbols")) }
    }

    static var clearSystemClipboard: Bool {
        get { ud.bool(forKey: key("clearSystemClipboard")) }
        set { ud.set(newValue, forKey: key("clearSystemClipboard")) }
    }

    // MARK: - Privacy defaults (HTML §17.10 / §19.6)
    //
    // Secret sources are hard-excluded by default and only recorded when the
    // user opts in. This switch does NOT touch structural transient types
    // (autoGenerated/concealed/transient) or the pause gesture — only the
    // credential-manager exclusions (ignoredApps/ignoredPasteboardTypes/
    // ignoreRegexp/ignoreHandoff) are bypassed when true.
    static var includeSecretSources: Bool {
        get { ud.bool(forKey: key("includeSecretSources")) }
        set { ud.set(newValue, forKey: key("includeSecretSources")) }
    }

    // Retention in DAYS. Default 30 (HTML §17.10). 0 = never expire.
    // Deliberately a free integer, not a fixed enum: 1/7/30 are only the
    // "common practice" shortcuts offered in Settings; the user may pick any
    // number. Expiry is computed from lastCopiedAt; pinned cards are exempt.
    static var retentionDays: Int {
        get {
            if ud.object(forKey: key("retentionDays")) == nil { return 30 }
            return ud.integer(forKey: key("retentionDays"))
        }
        set { ud.set(newValue, forKey: key("retentionDays")) }
    }
}

/// Pin change for `Logging`. Keeps the `Logger(label:)` / `.info` call sites.
struct Logger {
    private let subsystem: String
    private let osLogger: OSLog

    init(label: String) {
        subsystem = label
        osLogger = OSLog(subsystem: label, category: "default")
    }

    func info(_ message: String) {
        os_log("%{public}@", log: osLogger, type: .info, message)
    }

    func error(_ message: String) {
        os_log("%{public}@", log: osLogger, type: .error, message)
    }
}

