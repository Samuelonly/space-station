import AppKit
import Carbon.HIToolbox

// Pasteboard capture engine — see THIRD_PARTY_LICENSES for the MIT engine-base attribution.
// Pins (documented):
//  - `Defaults[.x]` -> `SS.x`                 (config helper, no SPM)
//  - source marker namespaced to this app
//  - `AppState.shared.history` -> `History.shared`
//  - `Sauce` / `KeyChord` / `KeyboardLayout` in paste() -> local V-keycode
//    (keyboard 底座 is M4; see HTML §21.5.5). Everything else — change-count
//    guard, ignore order, content merge, Microsoft type stripping, hook
//    dispatch — follows source lines 161-248 exactly.
@MainActor
final class Clipboard {
    static let shared = Clipboard()

    typealias OnNewCopyHook = (HistoryItem) -> Void

    private var onNewCopyHooks: [OnNewCopyHook] = []
    var changeCount: Int

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?

    private let dynamicTypePrefix = "dyn."
    private let microsoftSourcePrefix = "com.microsoft.ole.source."
    private let supportedTypes: Set<NSPasteboard.PasteboardType> = [
        .fileURL, .html, .png, .rtf, .string, .tiff
    ]
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .autoGenerated, .concealed, .transient
    ]
    private let unpersistableTypes: Set<NSPasteboard.PasteboardType> = [
        .appleWebArchive, .safariWebArchve
    ]

    private var enabledTypes: Set<NSPasteboard.PasteboardType> { SS.enabledPasteboardTypes }
    private var disabledTypes: Set<NSPasteboard.PasteboardType> {
        supportedTypes.subtracting(enabledTypes)
    }
    private var sourceApp: NSRunningApplication? { NSWorkspace.shared.frontmostApplication }

    init() {
        changeCount = pasteboard.changeCount
    }

    func onNewCopy(_ hook: @escaping OnNewCopyHook) {
        onNewCopyHooks.append(hook)
    }

    func clearHooks() {
        onNewCopyHooks = []
    }

    func start() {
        timer = Timer.scheduledTimer(
            timeInterval: SS.clipboardCheckInterval,
            target: self,
            selector: #selector(checkForChangesInPasteboard),
            userInfo: nil,
            repeats: true
        )
    }

    func restart() {
        timer?.invalidate()
        start()
    }

    func isPersistable(_ type: NSPasteboard.PasteboardType) -> Bool {
        !unpersistableTypes.contains(type) &&
            !type.rawValue.hasPrefix(microsoftSourcePrefix) &&
            !type.rawValue.hasPrefix(dynamicTypePrefix)
    }

    // Clipboard.swift:76-82 — write a string we made ourselves (search box etc.).
    func copyInStation(_ string: String) {
        pasteboard.clearContents()
        pasteboard.setString(string, forType: .string)
        pasteboard.setString(NSPasteboard.PasteboardType.fromStation.rawValue, forType: .source)
        sync()
        checkForChangesInPasteboard()
    }

    // Clipboard.swift:85-120 — copy a stored item back to the system clipboard.
    func copy(_ item: HistoryItem?, removeFormatting: Bool = false) {
        guard let item else { return }

        pasteboard.clearContents()
        var contents = item.contents
        if removeFormatting {
            contents = clearFormatting(contents)
        }

        for content in contents {
            guard content.type != NSPasteboard.PasteboardType.fileURL.rawValue else { continue }
            pasteboard.setData(content.value, forType: NSPasteboard.PasteboardType(content.type))
        }

        // writeObjects for file URLs so multiple files actually work (:100-110).
        let fileURLItems: [NSPasteboardItem] = contents.compactMap { content in
            guard content.type == NSPasteboard.PasteboardType.fileURL.rawValue,
                  let value = content.value else { return nil }
            let pasteItem = NSPasteboardItem()
            pasteItem.setData(value, forType: NSPasteboard.PasteboardType(content.type))
            return pasteItem
        }
        pasteboard.writeObjects(fileURLItems)

        pasteboard.setString("", forType: .fromStation)
        pasteboard.setString(item.application ?? "", forType: .source)
        sync()

        Task {
            checkForChangesInPasteboard()
        }
    }

    // Clipboard.swift:123-149 — pin: keyboard 底座 (Sauce/KeyChord/KeyboardLayout)
    // is deferred to M4. Using the QWERTY V keycode here keeps copy-back working.
    func paste() {
        let cmdFlag = NSEvent.ModifierFlags.command
        let vCode = UInt16(kVK_ANSI_V)
        let source = CGEventSource(stateID: .combinedSessionState)
        source?.setLocalEventsFilterDuringSuppressionState(
            [.permitLocalMouseEvents, .permitSystemDefinedEvents],
            state: .eventSuppressionStateSuppressionInterval
        )
        let down = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: false)
        down?.flags = CGEventFlags(rawValue: UInt64(cmdFlag.rawValue))
        up?.flags = CGEventFlags(rawValue: UInt64(cmdFlag.rawValue))
        down?.post(tap: .cgSessionEventTap)
        up?.post(tap: .cgSessionEventTap)
    }

    func clear() {
        guard SS.clearSystemClipboard else { return }
        pasteboard.clearContents()
    }

    // Clipboard.swift:161-240 — the capture chain, verbatim order.
    @objc
    func checkForChangesInPasteboard() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        // External copy stops the current paste stack (:168-172).
        if pasteboard.pasteboardItems?.contains(where: { $0.types.contains(.fromStation) }) != true {
            History.shared.interruptPasteStack()
        }

        // Pause / ignore-once (:174-181).
        if SS.ignoreEvents {
            if SS.ignoreOnlyNextEvent {
                SS.ignoreEvents = false
                SS.ignoreOnlyNextEvent = false
            }
            return
        }

        // Types read from NSPasteboard include all available types (:183-188).
        if shouldIgnore(Set(pasteboard.types ?? [])) { return }

        // Per-app bundleID hard exclusion (:190-192).
        if let sourceAppBundle = sourceApp?.bundleIdentifier, shouldIgnore(sourceAppBundle) { return }

        // Merge all pasteboard items into one record (:194-223).
        var contents = [HistoryItemContent]()
        pasteboard.pasteboardItems?.forEach { item in
            var types = Set(item.types)
            if types.contains(.string) && isEmptyString(item) && !richText(item) {
                return
            }
            if shouldIgnore(item) { return }

            types = types
                .subtracting(disabledTypes)
                .filter(isPersistable)

            // Avoid Word bookmarks/cross-references (:213-218).
            if types.isSuperset(of: [.microsoftLinkSource, .microsoftObjectLink]) {
                types = types.subtracting([.microsoftLinkSource, .microsoftObjectLink, .pdf])
            }

            types.forEach { type in
                contents.append(HistoryItemContent(type: type.rawValue, value: item.data(forType: type)))
            }
        }

        guard !contents.isEmpty else { return }

        let historyItem = HistoryItem(contents: contents)
        historyItem.application = sourceApp?.bundleIdentifier
        historyItem.title = historyItem.generateTitle()

        // Pin #1: hook dispatch (:239). PredictionEngine hangs metadata here in M3.
        onNewCopyHooks.forEach { $0(historyItem) }
    }

    // :242-248 + our Handoff enhancement (HTML §21.5.3).
    // HTML §19.6: secret-source exclusions are bypassed only when the user
    // opts in via SS.includeSecretSources. Structural transient types
    // (autoGenerated/concealed/transient) are always excluded regardless.
    private func shouldIgnore(_ types: Set<NSPasteboard.PasteboardType>) -> Bool {
        var ignored = self.ignoredTypes
        if !SS.includeSecretSources {
            ignored.formUnion(SS.ignoredPasteboardTypes.map({ NSPasteboard.PasteboardType($0) }))
            if SS.ignoreHandoff {
                ignored.insert(.universalClipboard)
            }
        }
        return types.isDisjoint(with: enabledTypes) || !types.isDisjoint(with: ignored)
    }

    // Ignored-app filtering (ignoreApps / ignoreAllAppsExceptListed).
    // Bypassed when secret sources are opted in (§19.6).
    private func shouldIgnore(_ sourceAppBundle: String) -> Bool {
        guard !SS.includeSecretSources else { return false }
        if SS.ignoreAllAppsExceptListed {
            return !SS.ignoredApps.contains(sourceAppBundle)
        }
        return SS.ignoredApps.contains(sourceAppBundle)
    }

    // :258-272 — regex ignore. Bypassed when secret sources are opted in.
    private func shouldIgnore(_ item: NSPasteboardItem) -> Bool {
        guard !SS.includeSecretSources else { return false }
        for regexp in SS.ignoreRegexp {
            if let string = item.string(forType: .string) {
                do {
                    let regex = try NSRegularExpression(pattern: regexp)
                    if regex.numberOfMatches(in: string, range: NSRange(string.startIndex..., in: string)) > 0 {
                        return true
                    }
                } catch {
                    return false
                }
            }
        }
        return false
    }

    private func isEmptyString(_ item: NSPasteboardItem) -> Bool {
        guard let string = item.string(forType: .string) else { return true }
        return string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    private func richText(_ item: NSPasteboardItem) -> Bool {
        if let rtf = item.data(forType: .rtf),
           let attributed = NSAttributedString(rtf: rtf, documentAttributes: nil) {
            return !attributed.string.isEmpty
        }
        if let html = item.data(forType: .html),
           let attributed = NSAttributedString(html: html, documentAttributes: nil) {
            return !attributed.string.isEmpty
        }
        return false
    }

    // :298-310 — window unfocus/refocus sync for stubborn apps.
    private func sync() {
        guard let app = sourceApp,
              app.bundleURL?.lastPathComponent == "Chrome Remote Desktop.app" ||
                app.localizedName?.contains("NetBeans") == true else { return }
        NSApp.activate(ignoringOtherApps: true)
        NSApp.hide(self)
    }

    private func clearFormatting(_ contents: [HistoryItemContent]) -> [HistoryItemContent] {
        var newContents = contents
        let stringContents = contents.filter { NSPasteboard.PasteboardType($0.type) == .string }
        if !stringContents.isEmpty {
            newContents = stringContents
            let fileURLContents = contents.filter { NSPasteboard.PasteboardType($0.type) == .fileURL }
            if !fileURLContents.isEmpty {
                newContents += fileURLContents
            }
        }
        return newContents
    }
}
